#!/usr/bin/env python3
"""Characterise the dataset WITHOUT exposing it to Claude.

This is the script half of the workflow in CLAUDE.md section 0.2:

    Claude writes this  ->  YOU run it  ->  it writes reports/eda/raw/  (quarantined)
                        ->  YOU promote safe aggregates to reports/eda/shared/
                        ->  Claude reads reports/eda/shared/ and helps you act on it

Nothing here prints data values to stdout. Everything goes to files under
`reports/eda/raw/`, which is git-ignored and blocked from Claude by both the settings deny
rules and the PreToolUse hook. It writes TWO files:

  raw/dataset_profile.json   full detail, including per-uid rows. NEVER share this.
  raw/SHARED_DRAFT.md        pre-aggregated summary, safe to promote after you read it.

The draft is written to `raw/` on purpose: you must read it yourself and consciously move it
to `shared/` rather than having a script decide what is safe on your behalf.

Usage:
    python scripts/01_inspect_data.py
    python scripts/01_inspect_data.py --limit 200        # quick pass while iterating
"""

from __future__ import annotations


import argparse
import json
import sys
from collections import Counter
from pathlib import Path

import numpy as np
import pandas as pd

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT / "src"))

from datpd.data.io import read_header_only  # noqa: E402
from datpd.data.splits import acquisition_signature  # noqa: E402

RAW_OUT = REPO_ROOT / "reports" / "eda" / "raw"


def profile_headers(nifti_dir: Path, limit: int | None) -> pd.DataFrame:
    """Read shape/spacing/dtype for every scan. Header-only, so this is fast and low-memory."""
    paths = sorted(nifti_dir.glob("*.nii.gz"))
    if limit:
        paths = paths[:limit]
    if not paths:
        raise SystemExit(f"No .nii.gz files found in {nifti_dir}. Download the data first.")

    rows = []
    for i, path in enumerate(paths, 1):
        info = read_header_only(path)
        uid = path.name.replace(".nii.gz", "")
        rows.append(
            {
                "uid": uid,
                "shape": info["shape"],
                "spacing_mm": info["spacing_mm"],
                "dtype": info["dtype"],
                "orientation": info["orientation"],
                "signature": acquisition_signature(info["shape"], info["spacing_mm"]),
                "extent_mm": tuple(
                    round(n * s, 1) for n, s in zip(info["shape"], info["spacing_mm"])
                ),
                "file_mb": round(path.stat().st_size / 1e6, 2),
            }
        )
        if i % 200 == 0:
            print(f"  ...{i}/{len(paths)} headers read", flush=True)
    return pd.DataFrame(rows)


# Groups smaller than this are aggregated into a single "tail" row rather than listed.
#
# This is not cosmetic. A signature with n=1 and a 100% positive rate IS that patient's
# diagnosis, and the signature is a lookup key back into dataset_profile.json, which holds the
# uids. Enumerating the tail turns an "aggregates only" file into per-patient disclosure -
# exactly what CLAUDE.md 0.3 forbids - and reports/eda/shared/ is git-tracked in a repository
# that winners must publish under MIT.
MIN_REPORTABLE_GROUP = 20


def _summarise_tail(rows: list[tuple[str, int, float | None]], total: int) -> list[str]:
    """Collapse every below-threshold group into one row. Never lists them individually."""
    small = [(sig, n, rate) for sig, n, rate in rows if n < MIN_REPORTABLE_GROUP]
    if not small:
        return []

    n_small = sum(n for _, n, _ in small)
    line = f"| _{len(small)} smaller signatures (aggregated)_ | {n_small} | {n_small / total:.1%} |"
    rates = [rate for _, n, rate in small if rate is not None]
    if rates:
        pooled = sum(r * n for (_, n, r) in small if r is not None) / max(n_small, 1)
        line = (
            f"| _{len(small)} smaller signatures (aggregated)_ | {n_small} | {pooled:.1%} |"
        )
    return [line]


def build_shared_draft(headers: pd.DataFrame, labels: pd.DataFrame | None) -> str:
    """Aggregate-only markdown. No uids, no per-row values, no small-group rows."""
    lines: list[str] = [
        "# Dataset profile (aggregates only)",
        "",
        "Generated by `scripts/01_inspect_data.py`. Review this file, confirm it contains no",
        "per-sample information, then move it to `reports/eda/shared/` for Claude to read.",
        "",
        "## Volume counts",
        f"- Scans profiled: **{len(headers)}**",
        "",
        "## Acquisition geometry",
        "",
        "Acquisition signatures — a proxy for centre/scanner, used as CV groups by",
        "`datpd.data.splits.add_folds`. Signatures below the reporting threshold are collapsed",
        "into one row: a group of one would disclose that patient's label "
        f"(threshold: n >= {MIN_REPORTABLE_GROUP}).",
        "",
        "| signature | n | share |",
        "|---|---:|---:|",
    ]
    sig_counts = headers["signature"].value_counts()
    for sig, n in sig_counts.items():
        if n >= MIN_REPORTABLE_GROUP:
            lines.append(f"| `{sig}` | {n} | {n / len(headers):.1%} |")
    lines += _summarise_tail(
        [(str(sig), int(n), None) for sig, n in sig_counts.items()], len(headers)
    )

    lines += [
        "",
        f"- Distinct signatures: **{len(sig_counts)}**",
        f"- Distinct shapes: **{headers['shape'].astype(str).nunique()}**",
        f"- Distinct spacings: **{headers['spacing_mm'].astype(str).nunique()}**",
        f"- Orientations present: {sorted(headers['orientation'].unique().tolist())}",
        f"- Voxel dtypes present: {sorted(headers['dtype'].unique().tolist())}",
        "",
        "## Physical field of view (mm)",
        "",
        "| axis | min | p25 | median | p75 | max |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    extents = np.array(headers["extent_mm"].tolist(), dtype=float)
    for axis, name in enumerate(("x", "y", "z")):
        q = np.percentile(extents[:, axis], [0, 25, 50, 75, 100])
        lines.append(
            f"| {name} | {q[0]:.0f} | {q[1]:.0f} | {q[2]:.0f} | {q[3]:.0f} | {q[4]:.0f} |"
        )

    lines += [
        "",
        f"- Total size on disk: **{headers['file_mb'].sum() / 1000:.2f} GB**",
        f"- Mean file size: **{headers['file_mb'].mean():.2f} MB**",
        "",
    ]

    if labels is not None:
        n = len(labels)
        pos = float(labels["is_pathologic"].mean())
        prior_ll = -(pos * np.log(pos) + (1 - pos) * np.log(1 - pos))
        lines += [
            "## Labels",
            f"- Labelled examinations: **{n}**",
            f"- Positive (`is_pathologic=1`) rate: **{pos:.3%}**",
            f"- Class counts: **{int(labels['is_pathologic'].sum())} positive / "
            f"{int(n - labels['is_pathologic'].sum())} negative**",
            "",
            f"- **Prior-only log loss baseline: {prior_ll:.4f}** "
            "(predict the base rate for everything; any model must beat this)",
            "",
            "### Class balance by acquisition signature",
            "",
            "A large swing across signatures means centre correlates with label — grouped CV",
            "is then mandatory, and centre-robustness matters more than raw CV score.",
            "",
            "| signature | n | positive rate |",
            "|---|---:|---:|",
        ]
        merged = headers.merge(labels, on="uid", how="inner")
        by_sig = [
            (str(sig), len(grp), float(grp["is_pathologic"].mean()))
            for sig, grp in merged.groupby("signature")
        ]
        by_sig.sort(key=lambda row: row[1], reverse=True)

        for sig, n, rate in by_sig:
            if n >= MIN_REPORTABLE_GROUP:
                lines.append(f"| `{sig}` | {n} | {rate:.1%} |")
        lines += _summarise_tail(by_sig, len(merged))
        lines += [
            "",
            f"Signatures with n < {MIN_REPORTABLE_GROUP} are pooled into the row above rather "
            "than listed. Listing them would publish individual diagnoses (CLAUDE.md §0.3).",
        ]

    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--nifti-dir", default="data/raw/niftis")
    parser.add_argument("--labels", default="data/raw/train_labels.csv")
    parser.add_argument("--limit", type=int, default=None)
    args = parser.parse_args()

    nifti_dir = REPO_ROOT / args.nifti_dir
    labels_path = REPO_ROOT / args.labels
    RAW_OUT.mkdir(parents=True, exist_ok=True)

    print(f"Profiling headers in {nifti_dir} ...", flush=True)
    headers = profile_headers(nifti_dir, args.limit)

    labels = None
    if labels_path.exists():
        labels = pd.read_csv(labels_path)
        print(f"Loaded labels: {len(labels)} rows", flush=True)
    else:
        print(f"No labels file at {labels_path} (fine for test-set profiling)", flush=True)

    detail_path = RAW_OUT / "dataset_profile.json"
    headers.to_json(detail_path, orient="records", indent=2)

    draft_path = RAW_OUT / "SHARED_DRAFT.md"
    draft_path.write_text(build_shared_draft(headers, labels), encoding="utf-8")

    print("")
    print(f"  detail (DO NOT SHARE) -> {detail_path.relative_to(REPO_ROOT)}")
    print(f"  aggregate draft       -> {draft_path.relative_to(REPO_ROOT)}")
    print("")
    print("Next: read SHARED_DRAFT.md yourself, confirm it has no per-sample values, then")
    print("      copy it to reports/eda/shared/dataset_profile.md so Claude can read it.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())


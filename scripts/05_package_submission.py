#!/usr/bin/env python3
"""Build submission.zip for the DrivenData code-execution platform.

Vendors the parts of `src/datpd/` that inference needs into the zip as `datpd_vendored/`, so
the submission has no dependency on this repo's layout. Preprocessing MUST be byte-identical
between training and inference; vendoring the same modules is how that is guaranteed.

Also runs a set of pre-flight checks. Every one of these corresponds to a way real submissions
fail on the platform, where the feedback loop is hours long.

Usage:
    python scripts/05_package_submission.py
    python scripts/05_package_submission.py --temperature 1.42 --fallback 0.38
"""

from __future__ import annotations

import argparse
import ast
import re
import shutil
import sys
import zipfile
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
SUBMISSION_SRC = REPO_ROOT / "submission_src"
BUILD_DIR = REPO_ROOT / "submission" / "build"
ZIP_PATH = REPO_ROOT / "submission" / "submission.zip"

# Modules copied from src/datpd into the zip. Keep this list minimal: everything shipped is
# something that can break at inference.
VENDORED = [
    ("data/__init__.py", "datpd_vendored/data/__init__.py"),
    ("data/io.py", "datpd_vendored/data/io.py"),
    ("data/preprocess.py", "datpd_vendored/data/preprocess.py"),
    ("models/__init__.py", "datpd_vendored/models/__init__.py"),
    ("models/resnet3d.py", "datpd_vendored/models/resnet3d.py"),
]

# The vendored top-level `__init__.py` is generated rather than copied: the real
# `src/datpd/__init__.py` re-exports the config machinery, which is training-only and is not
# shipped. Copying it and commenting out the import leaves a module whose `__all__` names
# nothing that exists - fine until someone writes `from datpd_vendored import *` at 2am.
VENDORED_INIT = '''"""Vendored subset of `datpd`, generated by scripts/05_package_submission.py.

Contains only what inference needs: volume loading, preprocessing, and the model definition.
These files are byte-identical copies of the training modules, which is what guarantees that
inference preprocessing matches training preprocessing.
"""
'''

# Packages guaranteed present in the official runtime (CLAUDE.md section 3).
RUNTIME_PACKAGES = {
    "accelerate", "antspyx", "attrs", "certifi", "cloudpickle", "dill", "diskcache", "einops",
    "filelock", "fsspec", "huggingface_hub", "importlib_metadata", "jsonpickle", "lightgbm",
    "loguru", "matplotlib", "monai", "more_itertools", "nibabel", "ninja", "numba", "numpy",
    "cv2", "packaging", "pandas", "peft", "PIL", "polars", "psutil", "pydantic",
    "pydantic_settings", "pytorch_lightning", "yaml", "regex", "requests", "safetensors",
    "skimage", "sklearn", "scipy", "SimpleITK", "statsmodels", "timm", "tokenizers", "torch",
    "torchio", "torchvision", "tqdm", "transformers", "urllib3", "xarray", "xgboost",
    "keras_cv_attention_models", "tensorflow", "tf_keras",
}
STDLIB_OK = set(sys.stdlib_module_names)


def check_imports(files: list[Path]) -> list[str]:
    """Flag any import that will not resolve inside the runtime container."""
    problems = []
    local = {"datpd_vendored", "datpd"}
    for path in files:
        tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
        for node in ast.walk(tree):
            names = []
            if isinstance(node, ast.Import):
                names = [a.name.split(".")[0] for a in node.names]
            elif isinstance(node, ast.ImportFrom) and node.level == 0 and node.module:
                names = [node.module.split(".")[0]]
            for name in names:
                if name not in STDLIB_OK and name not in RUNTIME_PACKAGES and name not in local:
                    problems.append(f"{path.name}: imports '{name}', not in the runtime")
    return problems


def check_checkpoints(checkpoints: list[Path], baked: dict[str, object]) -> list[str]:
    """Load every shipped checkpoint into the exact architecture `main.py` will construct.

    The one pre-flight check that catches an entire class of failure the others cannot: weights
    that are fine in themselves but do not fit the model the submission builds. A `widths`
    change in the config after training, a resume checkpoint copied in by mistake, a truncated
    file — all of them pass an import scan and a zip listing, and all of them fail on the
    platform hours later with nothing to show for the run.

    Cheap insurance: this is a few seconds of CPU against a lost submission slot.
    """
    if not checkpoints:
        return []

    sys.path.insert(0, str(REPO_ROOT / "src"))
    try:
        import torch

        from datpd.models.resnet3d import ResNet3D
    except ImportError as exc:  # torch missing locally is not a reason to block packaging
        return [f"could not verify checkpoints ({exc}); shipping them unchecked"]

    widths = tuple(baked.get("MODEL_WIDTHS", (16, 32, 64, 128)))  # type: ignore[arg-type]
    dropout = float(baked.get("MODEL_DROPOUT", 0.3))  # type: ignore[arg-type]

    problems = []
    for path in checkpoints:
        try:
            state = torch.load(path, map_location="cpu", weights_only=True)
            ResNet3D(widths=widths, dropout=dropout).load_state_dict(state)
        except Exception as exc:  # noqa: BLE001 - any failure here means do not ship
            problems.append(
                f"assets/{path.name}: does not load into ResNet3D(widths={widths}) "
                f"- {type(exc).__name__}"
            )
    return problems


def check_independence(main_py: Path) -> list[str]:
    """Heuristic scan for patterns that violate per-sample independence (CLAUDE.md 1.1)."""
    text = main_py.read_text(encoding="utf-8")
    problems = []
    banned = {
        r"\.fit\s*\(": "calls .fit() at inference - no fitting on test data",
        r"model\.train\s*\(": "puts a model in train mode - BatchNorm would use test batch stats",
        r"pseudo": "mentions pseudo-labelling",
    }
    for pattern, why in banned.items():
        if re.search(pattern, text, flags=re.IGNORECASE):
            problems.append(f"main.py: {why}")
    if "model.eval()" not in text and ".eval()" not in text:
        problems.append("main.py: no .eval() call found - models must be in eval mode")
    return problems


def build(baked: dict[str, object], prior_only: bool = False) -> int:
    if BUILD_DIR.exists():
        shutil.rmtree(BUILD_DIR)
    BUILD_DIR.mkdir(parents=True)

    shutil.copy2(SUBMISSION_SRC / "main.py", BUILD_DIR / "main.py")

    (BUILD_DIR / "datpd_vendored").mkdir(parents=True, exist_ok=True)
    (BUILD_DIR / "datpd_vendored" / "__init__.py").write_text(VENDORED_INIT, encoding="utf-8")

    for src_rel, dst_rel in VENDORED:
        dst = BUILD_DIR / dst_rel
        dst.parent.mkdir(parents=True, exist_ok=True)
        # copy2, not a rewrite: the vendored modules are deliberately free of imports from the
        # training-only parts of the package, so they need no patching to resolve. If that ever
        # stops being true, the fix belongs in the module, not in a regex here.
        shutil.copy2(REPO_ROOT / "src" / "datpd" / src_rel, dst)

    # Bake constants into main.py so nothing is fitted, inferred or defaulted at inference.
    main_path = BUILD_DIR / "main.py"
    main_text = main_path.read_text(encoding="utf-8")
    for name, value in baked.items():
        main_text, count = re.subn(
            rf"^{name} = .*$", f"{name} = {value!r}" if isinstance(value, str) else f"{name} = {value}",
            main_text, flags=re.MULTILINE,
        )
        if count != 1:
            raise SystemExit(f"could not bake {name} into main.py ({count} matches)")
    main_path.write_text(main_text, encoding="utf-8")

    problems: list[str] = []

    assets_src = SUBMISSION_SRC / "assets"
    all_pt = sorted(assets_src.glob("*.pt"))

    # Resume checkpoints are dicts of {model, optimizer, scheduler, ...}, not state_dicts, and
    # they match main.py's `fold*.pt` glob. Copied in by a careless `cp models/<run>/fold*.pt`,
    # one would be loaded as a model and crash inference at startup — after upload.
    resume_files = [p for p in all_pt if p.name.endswith("_last.pt")]
    checkpoints = [p for p in all_pt if p not in resume_files]
    if resume_files:
        names = ", ".join(p.name for p in resume_files)
        problems.append(f"assets/: remove the resume checkpoints before packaging ({names})")

    problems += check_checkpoints(checkpoints, baked)

    if checkpoints:
        (BUILD_DIR / "assets").mkdir(exist_ok=True)
        for ckpt in checkpoints:
            shutil.copy2(ckpt, BUILD_DIR / "assets" / ckpt.name)

    py_files = sorted(BUILD_DIR.rglob("*.py"))
    problems += check_imports(py_files) + check_independence(main_path)

    print("Pre-flight checks")
    print(f"  python files vendored : {len(py_files)}")
    print(f"  model checkpoints     : {len(checkpoints)}")
    for name, value in baked.items():
        print(f"  {name:<21} : {value}")

    if not checkpoints and not prior_only:
        problems.append("assets/: no checkpoints - submission would predict the prior")
    if prior_only and checkpoints:
        problems.append("--prior-only was passed but assets/ has checkpoints; drop the flag")

    if problems:
        print("\nFAILED:")
        for p in problems:
            print(f"  - {p}")
        return 1
    print("  all checks passed")

    ZIP_PATH.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(ZIP_PATH, "w", zipfile.ZIP_DEFLATED) as zf:
        for path in sorted(BUILD_DIR.rglob("*")):
            if path.is_file():
                zf.write(path, path.relative_to(BUILD_DIR))

    size_mb = ZIP_PATH.stat().st_size / 1e6
    try:
        shown = ZIP_PATH.relative_to(REPO_ROOT)
    except ValueError:
        shown = ZIP_PATH  # building outside the repo, e.g. under a test's tmp_path
    print(f"\nWrote {shown} ({size_mb:.1f} MB)")
    if prior_only:
        print("\nPRIOR-ONLY BUILD: this predicts a constant for every row. Its purpose is to")
        print("prove the platform contract end to end before a model exists, not to score.")
    print("Next: test it in the runtime repo with `just pack-submission && just test-submission`")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", default=None,
                        help="training config whose preprocessing/architecture to bake in; "
                             "omit only for a prior-only build")
    parser.add_argument("--temperature", type=float, default=None,
                        help="fitted OOF temperature to bake into main.py")
    parser.add_argument("--fallback", type=float, default=None,
                        help="training positive rate, used when a scan fails to load")
    parser.add_argument("--clip-eps", type=float, default=None,
                        help="prediction clip chosen on OOF by scripts/04_evaluate.py")
    parser.add_argument("--prior-only", action="store_true",
                        help="package a valid submission with no weights, predicting --fallback "
                             "for every row. Use on day 1 to validate the platform loop.")
    args = parser.parse_args()

    baked: dict[str, object] = {}
    if args.temperature is not None:
        baked["TEMPERATURE"] = args.temperature
    if args.fallback is not None:
        baked["FALLBACK_PROB"] = args.fallback
    if args.clip_eps is not None:
        baked["CLIP_EPS"] = args.clip_eps

    if args.config:
        # Bake the preprocessing and architecture the weights were actually trained with.
        # Reading them from the config rather than trusting main.py's defaults is what keeps
        # training and inference from drifting apart silently.
        sys.path.insert(0, str(REPO_ROOT / "src"))
        from datpd.config import load_config

        cfg = load_config(REPO_ROOT / args.config)
        baked["TARGET_SPACING"] = tuple(cfg.data.target_spacing_mm)
        baked["TARGET_SHAPE"] = tuple(cfg.data.target_shape)
        baked["NORMALIZATION"] = cfg.data.normalization
        baked["CROP"] = cfg.data.crop
        baked["MODEL_WIDTHS"] = tuple(cfg.model.widths)
        baked["MODEL_DROPOUT"] = cfg.model.dropout
    elif not args.prior_only:
        raise SystemExit("--config is required unless building with --prior-only")

    return build(baked, prior_only=args.prior_only)


if __name__ == "__main__":
    raise SystemExit(main())
